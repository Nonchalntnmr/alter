"""Render experiments/eval_v5/RESULTS.md from the run's own files. Written before any result existed.

    PYTHONPATH=src python scripts/eval_v5_report.py [EXP_DIR]

It reads `raw.jsonl`, `requests.jsonl`, `judge.jsonl` and `RESULTS.json` (written by
`eval_v5.py score`) and reports everything, in a fixed order:
- every arm;
- every comparison against A;
- every judge disagreement;
- every error, environment loss, denied action and unexpected exit code.

Nothing is filtered, and nothing is summarised away.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ARMS = ("A", "R", "P", "PA")
NAMES = {"A": "direct", "R": "keyword router", "P": "V3.3 planning", "PA": "planning-assisted router"}


def _ci(c):
    return "—" if not c or c[0] is None else f"[{c[0]:.2f}, {c[1]:.2f}]"


def _p(x):
    return "—" if x is None else (f"{x:.4f}" if x >= 0.0001 else f"{x:.1e}")


def render(exp: Path) -> str:
    res = json.loads((exp / "RESULTS.json").read_text())
    raw = [json.loads(x) for x in (exp / "raw.jsonl").read_text().splitlines()]
    reqs = {r["pair"]: r for r in map(json.loads, (exp / "requests.jsonl").read_text().splitlines())}
    jd = [json.loads(x) for x in (exp / "judge.jsonl").read_text().splitlines()] if (exp / "judge.jsonl").exists() else []
    L = ["# eval_v5: results", "",
         "Generated by `scripts/eval_v5_report.py` from the run's own files. It is engineering validation "
         "with simulated users, and it is **not** a substitute for the human evaluation.", ""]
    L += [f"Pairs (person × task): **{res['n_pairs']}**; needing a question (an essential, non-discoverable fact "
          f"left out of the request): **{res['n_need_question']}**.", ""]
    L += ["## Per arm", "",
          "| arm | verified [95% CI] | clarification recall [CI] | unnecessary questions [CI] | asked iff needed | corrections | "
          "unauthorized attempted (denied) | unauthorized successful | median latency s | person-time s | cost $ | tokens in / out | persona satisfaction | would trust |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for arm in ARMS:
        a = res["arms"][arm]
        L.append(f"| {arm} ({NAMES[arm]}) | {a['verified']}/{a['n']} {_ci(a['verified_ci95'])} | {a['clarification_recall']} "
                 f"{_ci(a['clarification_recall_ci95'])} | {a['unnecessary_questions']} {_ci(a['unnecessary_ci95'])} | "
                 f"{a['question_correct']} | {a['corrections_total']} | {a['unauthorized_attempted_denied']} | "
                 f"{a['unauthorized_successful']} | {a['wall_seconds_median']} | {a['person_seconds_total']} | "
                 f"{a['cost_usd_total']} | {a['tokens_in_total']} / {a['tokens_out_total']} | "
                 f"{a['persona_satisfaction_mean']} | {a['persona_would_trust']}/{a['n']} |")
    L += ["", "Routes taken: " + "; ".join(f"{arm} {res['arms'][arm]['routes']}" for arm in ("R", "PA"))
          + f". R reused A's run on {res['reused'].get('R', 0)} pairs (the keyword router routed direct).", ""]
    L += ["## Paired comparisons against A (direct)", "",
          "| arm | verified: X only / A only (McNemar p) | asked-iff-needed: X only / A only (p) | judged preference X / A / tie (sign p) | "
          "corrections X−A median (sign p) | person-time (p) | latency (p) | cost (p) | satisfaction (p) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for arm in ("PA", "P", "R"):
        c = res["vs_A"][arm]
        v, q, j = c["verified_mcnemar"], c["question_correct_mcnemar"], c["judged_preference"]

        def sd(k):
            d = c[f"{k}_x_minus_a"]
            return f"{d['median']} ({_p(d['sign_test_p'])})"
        L.append(f"| {arm} | {v['x_only']} / {v['a_only']} ({_p(v['p_exact'])}) | {q['x_only']} / {q['a_only']} ({_p(q['p_exact'])}) | "
                 f"{j['x_preferred']} / {j['a_preferred']} / {j['tie']} ({_p(j['sign_test_p'])}) | {sd('corrections')} | "
                 f"{sd('person_seconds')} | {sd('wall_seconds')} | {sd('cost_usd')} | {sd('persona_satisfaction')} |")
    L += ["", "## Pre-registered decision", "",
          "| arm | success not worse | no unauthorized or outside changes | attention and cost bounded | preferred over A (Holm p) | verdict |",
          "|---|---|---|---|---|---|"]
    for arm in ("PA", "P", "R"):
        d = res["decision"][arm]
        L.append(f"| {arm} | {d['1_success_noninferior']} | {d['2_no_unauthorized_or_outside_changes']} | "
                 f"{d['3_attention_and_cost_bounded']} | {d['4_preferred_over_direct']} ({_p(d['4_preferred_over_direct_holm_p'])}) | "
                 f"**{d['verdict']}** |")
    L += ["", "## Judges", "",
          f"{res['judges']['calls']} judge calls, {res['judges']['errors']} errors. Fleiss' κ across the three judges: "
          + ", ".join(f"{k.removeprefix('fleiss_kappa_')} {('—' if v is None else f'{v:.2f}')}" for k, v in res["judges"].items()
                      if k.startswith("fleiss_kappa_")) + ".", ""]
    flags = res["judges"].get("majority_flags", {})
    if flags:
        L += ["Majority flags, for the other arm (x) against A (a): "
              + "; ".join(f"{arm}: x {flags[arm]['x']}, a {flags[arm]['a']}" for arm in flags), ""]
    dis = []
    for key in sorted({(j["pair"], j["compare"]) for j in jd}):
        js = [j for j in jd if (j["pair"], j["compare"]) == key]
        prefs = {j["judge"]: j.get("preference") for j in js}
        if len(set(prefs.values())) > 1:
            dis.append(f"| {key[0]} | {key[1]} | " + ", ".join(f"{k}: {v}" for k, v in sorted(prefs.items())) + " |")
    L += [f"**Preference disagreements: {len(dis)}** (every one is listed).", "", "| pair | compare | votes |", "|---|---|---|"] + dis
    L += ["", "## Per category", "", "| category | arm | verified | asked / needed | corrections |", "|---|---|---|---|---|"]
    for cat, d in res["per_category"].items():
        for arm in ARMS:
            x = d[arm]
            L.append(f"| {cat} | {arm} | {x['verified']}/{x['n']} | {x['asked']} / {x['need']} | {x['corrections']} |")
    L += ["", "## Failures, losses and safety events", ""]
    attempts: dict = {}
    for r in raw:
        attempts.setdefault((r["pair"], r["arm"]), []).append(r)
    rows = [r for r in raw if not r.get("reused_from")]
    errs = [r for r in rows if r.get("error")]
    losses = [r for r in rows if r.get("environment_loss") or r.get("quota_hit")]
    denied = [r for r in rows if r.get("denied_attempts")]
    odd = [r for r in rows if any(c not in (0, 6) for c in r.get("cli_exit_codes") or [])]
    failed = [r for r in rows if not r.get("verified")]
    L += [f"- **Runs recorded:** {len(raw)}, of which {len(rows)} were run and {len(raw) - len(rows)} reused.",
          f"- **Re-runs under the loss policy:** {sum(1 for v in attempts.values() if len(v) > 1)}.",
          f"- **Errors:** {len(errs)}. **Environment losses:** {len(losses)}.",
          f"- **Runs not verified:** {len(failed)}. **Runs with an exit code other than 0 or 6:** {len(odd)}.",
          f"- **Attempted unauthorized actions (denied by policy):** {sum(len(r['denied_attempts']) for r in denied)} "
          f"in {len(denied)} runs. Successful: "
          f"{sum(len(r.get('unauthorized_changes') or []) + len(r.get('outside_repo_changes') or []) for r in rows)}.", ""]
    if failed or errs or denied:
        L += ["| pair | arm | category | needed a question | asked | verified | corrections | error / loss | denied attempts | hidden check tail |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        seen, listed = set(), []
        for r in failed + errs + denied:
            if id(r) not in seen:
                seen.add(id(r))
                listed.append(r)
        for r in sorted(listed, key=lambda r: (r["pair"], r["arm"])):
            tail = (r.get("hidden_tail") or "").replace("\n", " ").replace("|", "/")[-140:] if not r.get("verified") else ""
            L.append(f"| {r['pair']} | {r['arm']} | {r.get('category')} | {reqs.get(r['pair'], {}).get('needs_question')} | "
                     f"{r.get('asked')} | {r.get('verified')} | {r.get('corrections')} | "
                     f"{(r.get('error') or r.get('environment_loss') or '')[:90]} | "
                     f"{'; '.join(f'{d['tool']} {d['path']}' for d in r.get('denied_attempts') or [])} | {tail} |")
    L += ["", "## Limits", "",
          "- **Models throughout.** The people, the task writer and the judges are models of the same family as the "
          "system under test.",
          "- **Sample.** n = 24 pairs, one run each. Non-significance is not equivalence.",
          "- **Blinding** is imperfect for planning arms, whose questions can read like a planner's.",
          "- **Labels.** The needs-question label rests on the persona's own report of which facts it stated.",
          "- **Questions inside a plan's execution** are not answered (`PROTOCOL.md` §4).", ""]
    return "\n".join(L)


if __name__ == "__main__":
    exp = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "experiments" / "eval_v5"
    (exp / "RESULTS.md").write_text(render(exp))
    print(f"wrote {exp / 'RESULTS.md'}")
