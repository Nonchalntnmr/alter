"""Render experiments/eval_v8/RESULTS.md from the run's own files. Written before any result existed.

    PYTHONPATH=src python scripts/eval_v8_report.py [EXP_DIR]

It reports everything, in a fixed order:
- every arm;
- every comparison against A;
- verification calibration;
- every judge disagreement;
- every failure, loss and safety event.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ARMS = ("A", "G")
NAMES = {"A": "direct", "G": "ALTER goal"}


def _ci(c):
    return "—" if not c or c[0] is None else f"[{c[0]:.2f}, {c[1]:.2f}]"


def _r(m):
    return f"{m['k']}/{m['n']} {_ci(m['ci95'])}"


def _p(x):
    return "—" if x is None else (f"{x:.4f}" if x >= 0.0001 else f"{x:.1e}")


def render(exp: Path) -> str:
    res = json.loads((exp / "RESULTS.json").read_text())
    raw = [json.loads(x) for x in (exp / "raw.jsonl").read_text().splitlines()]
    reqs = {r["pair"]: r for r in map(json.loads, (exp / "requests.jsonl").read_text().splitlines())}
    L = ["# eval_v8: results (the V1 eval gate)", "",
         "Generated by `scripts/eval_v8_report.py` from the run's own files.",
         "- It is engineering validation with simulated users, and is **not** a substitute for the human evaluation.",
         "- The pool is enriched so that half the tasks need a question. That is not a claim about real-world frequency.",
         "",
         f"- **Pairs scored** (person × task): **{res['n_pairs']}/{res['n_pairs_expected']}**.",
         f"- **Needing a question:** **{res['n_need_question']}**, of which {res['n_need_tacit']} because of a tacit "
         "fact, the rest because the persona left a fact out.", ""]
    L += ["## Per arm", "",
          "| arm | success | first-pass success | clarification recall | precision | unnecessary questions | asked iff needed | "
          "corrections | unauthorized attempted (denied) | successful | median latency s | person-time s | cost $ | tokens in / out | "
          "satisfaction | would trust |", "|" + "---|" * 16]
    for arm in ARMS:
        a = res["arms"][arm]
        L.append(f"| {arm} ({NAMES[arm]}) | {_r(a['success'])} | {_r(a['first_pass_success'])} | {_r(a['clarification_recall'])} | "
                 f"{_r(a['clarification_precision'])} | {_r(a['unnecessary_questions'])} | {_r(a['question_correct'])} | "
                 f"{a['corrections_total']} | {a['unauthorized_attempted_denied']} | {a['unauthorized_successful']} | "
                 f"{a['wall_seconds_median']} | {a['person_seconds_total']} | {a['cost_usd_total']} | "
                 f"{a['tokens_in_total']} / {a['tokens_out_total']} | {a['persona_satisfaction_mean']} | "
                 f"{a['persona_would_trust']}/{a['success']['n']} |")
    L += ["", f"G's goals ended: {res['arms']['G']['goal_status']}.", ""]
    L += ["## Paired comparisons against A", "",
          "| arm | first pass: X only / A only (McNemar p) | success (p) | asked-iff-needed (p) | judged preference X / A / tie (sign p) | "
          "corrections X−A median (p) | person-time (p) | latency (p) | cost (p) | satisfaction (p) |", "|" + "---|" * 10]
    for arm in ("G",):
        c = res["vs_A"][arm]

        def m(k):
            return f"{c[k]['x_only']} / {c[k]['a_only']} ({_p(c[k]['p_exact'])})"

        def sd(k):
            d = c[f"{k}_x_minus_a"]
            return f"{d['median']} ({_p(d['sign_test_p'])})"
        j = c["judged_preference"]
        L.append(f"| {arm} | {m('first_pass_mcnemar')} | {m('verified_mcnemar')} | {m('question_correct_mcnemar')} | "
                 f"{j['x_preferred']} / {j['a_preferred']} / {j['tie']} ({_p(j['sign_test_p'])}) | {sd('corrections')} | "
                 f"{sd('person_seconds')} | {sd('wall_seconds')} | {sd('cost_usd')} | {sd('persona_satisfaction')} |")
    L += ["", "## Pre-registered decision (non-inferiority and safety; no superiority claimed)", "",
          "| arm | success not worse (≥ A − 2, not significantly worse) | no successful unauthorized | false done ≤ A | "
          "never done without evidence | attention ≤ 1.5 × A | cost ≤ 1.5 × A | verdict |", "|" + "---|" * 8]
    for arm in ("G",):
        d = res["decision"][arm]
        L.append(f"| {arm} | {d['1_success_not_worse']} | {d['2_no_successful_unauthorized']} | {d['3a_false_done_not_worse']} | "
                 f"{d['3b_never_done_without_evidence']} | {d['4_attention_bounded']} | {d['5_cost_bounded']} | **{d['verdict']}** |")
    L += ["", "## Verification calibration (`ci do`'s verdict against the hidden check)", "",
          "| arm | verified and passes | verified but fails | not verified but passes | claimed done without evidence | ...and failed | false done |",
          "|---|---|---|---|---|---|---|"]
    for arm in ARMS:
        a = res["arms"][arm]
        L.append(f"| {arm} | {a['ci_verified_and_hidden_pass']} | {a['ci_verified_but_hidden_fail']} | "
                 f"{a['ci_not_verified_but_hidden_pass']} | {a['ci_claim_unverified']} | {a['ci_claim_unverified_and_hidden_fail']} | "
                 f"{a['false_done']} |")
    jk = res["judges"]
    L += ["", "## Judges", "",
          f"{jk['calls']} judge calls, {jk['errors']} errors. Fleiss' κ: "
          + ", ".join(f"{k.removeprefix('fleiss_kappa_')} {('—' if v is None else f'{v:.2f}')}" for k, v in jk.items()
                      if k.startswith("fleiss_kappa_")) + ".", "",
          f"**Preference disagreements: {len(jk['preference_disagreements'])}** (every one is listed):", ""]
    L += [f"- {d}" for d in jk["preference_disagreements"]] or ["- none"]
    L += ["", "## Per category", "", "| category | arm | success | first pass | asked / needed | corrections |",
          "|---|---|---|---|---|---|"]
    for cat, d in res["per_category"].items():
        for arm in ARMS:
            x = d[arm]
            L.append(f"| {cat} | {arm} | {x['verified']}/{x['n']} | {x['first_pass']}/{x['n']} | {x['asked']} / {x['need']} | "
                     f"{x['corrections']} |")
    rows = [r for r in raw if not r.get("reused_from")]
    attempts: dict = {}
    for r in raw:
        attempts.setdefault((r["pair"], r["arm"]), []).append(r)
    failed = [r for r in rows if not r.get("verified")]
    events = [r for r in rows if r.get("denied_attempts")]
    L += ["", "## Failures, losses and safety events", "",
          f"- **Runs recorded:** {len(raw)}, of which {len(rows)} were run and {len(raw) - len(rows)} reused.",
          f"- **Re-runs under the loss policy:** {sum(1 for v in attempts.values() if len(v) > 1)}.",
          f"- **Errors:** {sum(1 for r in rows if r.get('error'))}. **Environment losses:** "
          f"{sum(1 for r in rows if r.get('environment_loss') or r.get('quota_hit'))}.",
          f"- **Runs not verified:** {len(failed)}.",
          f"- **Attempted unauthorized actions (denied):** {sum(len(r['denied_attempts']) for r in events)} in "
          f"{len(events)} runs.", ""]
    seen, listed = set(), []
    for r in failed + events:
        if id(r) not in seen:
            seen.add(id(r))
            listed.append(r)
    if listed:
        L += ["| pair | arm | category | needed a question | asked | verified | corrections | denied attempts | hidden check tail |",
              "|---|---|---|---|---|---|---|---|---|"]
        for r in sorted(listed, key=lambda r: (r["pair"], r["arm"])):
            denied = "; ".join(f"{d['tool']} {d['path']}" for d in r.get("denied_attempts") or [])
            tail = (r.get("hidden_tail") or "").replace("\n", " ").replace("|", "/")[-140:] if not r.get("verified") else ""
            L.append(f"| {r['pair']} | {r['arm']} | {r.get('category')} | {reqs.get(r['pair'], {}).get('needs_question')} | "
                     f"{r.get('asked')} | {r.get('verified')} | {r.get('corrections')} | {denied} | {tail} |")
    L += ["", "## Limits", "",
          "- **Models throughout.** The people, the task writer and the judges are models of the same family as the "
          "system under test.",
          "- **Sample.** n = 24 pairs, one run each. Non-significance is not equivalence.",
          "- **Enrichment.** Half the pool needs a question by design, which is not real-world frequency.",
          "- **Labels.** The fact labels (essential, discoverable, volunteered) are the writer's.",
          "- **G is more than one change.** G differs from A in the Third Eye brief, the goal instructions, verification "
          "prompts and the goal loop, so a difference cannot be split between them.",
          "- **Corrections differ in form.** A continues its conversation; G starts a follow-up goal carrying the request "
          "and the correction.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    exp = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1] / "experiments" / "eval_v8"
    (exp / "RESULTS.md").write_text(render(exp))
    print("wrote RESULTS.md")
